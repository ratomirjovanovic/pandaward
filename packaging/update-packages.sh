#!/bin/sh
# Writes the Homebrew formula, the Scoop manifest and the winget manifests
# for a published release from its SHA256SUMS.
#
#   sh packaging/update-packages.sh 0.1.2 [path/to/SHA256SUMS]
#
# Without a path the SHA256SUMS of the GitHub release is downloaded.
set -eu

[ $# -ge 1 ] || { echo "usage: $0 <version> [SHA256SUMS]" >&2; exit 2; }
version=$1
case "$version" in
v*) echo "give the version without the leading v" >&2; exit 2 ;;
esac
repo=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
base="https://github.com/ratomirjovanovic/pandaward/releases/download/v$version"

sums=${2:-}
if [ -z "$sums" ]; then
	sums=$(mktemp)
	trap 'rm -f "$sums"' EXIT
	curl -fsSL "$base/SHA256SUMS" -o "$sums"
fi

sum() {
	h=$(awk -v n="$1" '{ sub(/\r$/, "") } $2 == n || $2 == "*" n { print $1 }' "$sums")
	[ -n "$h" ] || { echo "no checksum for $1 in SHA256SUMS" >&2; exit 1; }
	echo "$h"
}

darwin_arm64=$(sum pandaward-darwin-arm64)
darwin_amd64=$(sum pandaward-darwin-amd64)
linux_arm64=$(sum pandaward-linux-arm64)
linux_amd64=$(sum pandaward-linux-amd64)
windows_amd64=$(sum pandaward-windows-amd64.exe)

desc="Local, evidence-based application security assessment"

mkdir -p "$repo/Formula"
cat > "$repo/Formula/pandaward.rb" <<EOF
# Generated by packaging/update-packages.sh; do not edit by hand.
class Pandaward < Formula
  desc "$desc"
  homepage "https://github.com/ratomirjovanovic/pandaward"
  version "$version"
  license "AGPL-3.0-only"

  on_macos do
    on_arm do
      url "$base/pandaward-darwin-arm64"
      sha256 "$darwin_arm64"
    end
    on_intel do
      url "$base/pandaward-darwin-amd64"
      sha256 "$darwin_amd64"
    end
  end

  on_linux do
    on_arm do
      url "$base/pandaward-linux-arm64"
      sha256 "$linux_arm64"
    end
    on_intel do
      url "$base/pandaward-linux-amd64"
      sha256 "$linux_amd64"
    end
  end

  def install
    bin.install Dir["pandaward-*"].first => "pandaward"
  end

  test do
    assert_match "pandaward #{version}", shell_output("#{bin}/pandaward version")
  end
end
EOF

mkdir -p "$repo/bucket"
cat > "$repo/bucket/pandaward.json" <<EOF
{
    "version": "$version",
    "description": "$desc.",
    "homepage": "https://github.com/ratomirjovanovic/pandaward",
    "license": "AGPL-3.0-only",
    "architecture": {
        "64bit": {
            "url": "$base/pandaward-windows-amd64.exe#/pandaward.exe",
            "hash": "$windows_amd64"
        }
    },
    "bin": "pandaward.exe"
}
EOF

wg="$repo/packaging/winget/$version"
mkdir -p "$wg"
id=RatomirJovanovic.Pandaward
cat > "$wg/$id.yaml" <<EOF
# Generated by packaging/update-packages.sh
# yaml-language-server: \$schema=https://aka.ms/winget-manifest.version.1.12.0.schema.json
PackageIdentifier: $id
PackageVersion: $version
DefaultLocale: en-US
ManifestType: version
ManifestVersion: 1.12.0
EOF
cat > "$wg/$id.installer.yaml" <<EOF
# Generated by packaging/update-packages.sh
# yaml-language-server: \$schema=https://aka.ms/winget-manifest.installer.1.12.0.schema.json
PackageIdentifier: $id
PackageVersion: $version
InstallerType: portable
Commands:
  - pandaward
Installers:
  - Architecture: x64
    InstallerUrl: $base/pandaward-windows-amd64.exe
    InstallerSha256: $(echo "$windows_amd64" | tr a-f A-F)
ManifestType: installer
ManifestVersion: 1.12.0
EOF
cat > "$wg/$id.locale.en-US.yaml" <<EOF
# Generated by packaging/update-packages.sh
# yaml-language-server: \$schema=https://aka.ms/winget-manifest.defaultLocale.1.12.0.schema.json
PackageIdentifier: $id
PackageVersion: $version
PackageLocale: en-US
Publisher: Ratomir Jovanovic
PublisherUrl: https://github.com/ratomirjovanovic
PackageName: Pandaward
PackageUrl: https://github.com/ratomirjovanovic/pandaward
License: AGPL-3.0-only
LicenseUrl: https://github.com/ratomirjovanovic/pandaward/blob/main/LICENSE
ShortDescription: $desc.
Description: Pandaward scans your own repository locally, keeps an evidence ledger across sessions and reports undecided controls as plainly as failed ones. Passive by default.
Tags:
  - security
  - appsec
  - sast
  - sarif
ReleaseNotesUrl: https://github.com/ratomirjovanovic/pandaward/releases/tag/v$version
ManifestType: defaultLocale
ManifestVersion: 1.12.0
EOF

written="Formula/pandaward.rb, bucket/pandaward.json and packaging/winget/$version"

# MCP Registry metadata, for releases that ship the MCPB bundle.
if mcpb=$(awk -v n="pandaward-mcp.mcpb" '{ sub(/\r$/, "") } $2 == n || $2 == "*" n { print $1 }' "$sums") && [ -n "$mcpb" ]; then
	cat > "$repo/server.json" <<EOF
{
  "\$schema": "https://static.modelcontextprotocol.io/schemas/2025-12-11/server.schema.json",
  "name": "io.github.ratomirjovanovic/pandaward",
  "title": "Pandaward",
  "description": "Local, evidence-based application security assessment with an evidence ledger and retests.",
  "repository": {
    "url": "https://github.com/ratomirjovanovic/pandaward",
    "source": "github"
  },
  "websiteUrl": "https://ratomirjovanovic.github.io/pandaward/",
  "version": "$version",
  "packages": [
    {
      "registryType": "mcpb",
      "identifier": "$base/pandaward-mcp.mcpb",
      "version": "$version",
      "fileSha256": "$mcpb",
      "transport": {
        "type": "stdio"
      }
    }
  ]
}
EOF
	written="$written, server.json"
fi

echo "Wrote $written for $version."

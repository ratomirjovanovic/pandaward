#!/bin/sh
# Writes the Homebrew formula, the Scoop manifest and the winget manifests
# for a published release from its SHA256SUMS.
#
#   sh packaging/update-packages.sh 0.1.2 [path/to/SHA256SUMS]
#
# Without a path the SHA256SUMS of the GitHub release is downloaded.
set -eu

[ $# -ge 1 ] || { echo "usage: $0 <version> [SHA256SUMS]" >&2; exit 2; }
version=$1
case "$version" in
v*) echo "give the version without the leading v" >&2; exit 2 ;;
esac
repo=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
base="https://github.com/ratomirjovanovic/pensec/releases/download/v$version"

sums=${2:-}
if [ -z "$sums" ]; then
	sums=$(mktemp)
	trap 'rm -f "$sums"' EXIT
	curl -fsSL "$base/SHA256SUMS" -o "$sums"
fi

sum() {
	h=$(awk -v n="$1" '{ sub(/\r$/, "") } $2 == n || $2 == "*" n { print $1 }' "$sums")
	[ -n "$h" ] || { echo "no checksum for $1 in SHA256SUMS" >&2; exit 1; }
	echo "$h"
}

darwin_arm64=$(sum pensec-darwin-arm64)
darwin_amd64=$(sum pensec-darwin-amd64)
linux_arm64=$(sum pensec-linux-arm64)
linux_amd64=$(sum pensec-linux-amd64)
windows_amd64=$(sum pensec-windows-amd64.exe)

desc="Local, evidence-based application security assessment"

mkdir -p "$repo/Formula"
cat > "$repo/Formula/pensec.rb" <<EOF
# Generated by packaging/update-packages.sh; do not edit by hand.
class Pensec < Formula
  desc "$desc"
  homepage "https://github.com/ratomirjovanovic/pensec"
  version "$version"
  license "AGPL-3.0-only"

  on_macos do
    on_arm do
      url "$base/pensec-darwin-arm64"
      sha256 "$darwin_arm64"
    end
    on_intel do
      url "$base/pensec-darwin-amd64"
      sha256 "$darwin_amd64"
    end
  end

  on_linux do
    on_arm do
      url "$base/pensec-linux-arm64"
      sha256 "$linux_arm64"
    end
    on_intel do
      url "$base/pensec-linux-amd64"
      sha256 "$linux_amd64"
    end
  end

  def install
    bin.install Dir["pensec-*"].first => "pensec"
  end

  test do
    assert_match "pensec #{version}", shell_output("#{bin}/pensec version")
  end
end
EOF

mkdir -p "$repo/bucket"
cat > "$repo/bucket/pensec.json" <<EOF
{
    "version": "$version",
    "description": "$desc.",
    "homepage": "https://github.com/ratomirjovanovic/pensec",
    "license": "AGPL-3.0-only",
    "architecture": {
        "64bit": {
            "url": "$base/pensec-windows-amd64.exe#/pensec.exe",
            "hash": "$windows_amd64"
        }
    },
    "bin": "pensec.exe"
}
EOF

wg="$repo/packaging/winget/$version"
mkdir -p "$wg"
id=RatomirJovanovic.PenSec
cat > "$wg/$id.yaml" <<EOF
# Generated by packaging/update-packages.sh
# yaml-language-server: \$schema=https://aka.ms/winget-manifest.version.1.12.0.schema.json
PackageIdentifier: $id
PackageVersion: $version
DefaultLocale: en-US
ManifestType: version
ManifestVersion: 1.12.0
EOF
cat > "$wg/$id.installer.yaml" <<EOF
# Generated by packaging/update-packages.sh
# yaml-language-server: \$schema=https://aka.ms/winget-manifest.installer.1.12.0.schema.json
PackageIdentifier: $id
PackageVersion: $version
InstallerType: portable
Commands:
  - pensec
Installers:
  - Architecture: x64
    InstallerUrl: $base/pensec-windows-amd64.exe
    InstallerSha256: $(echo "$windows_amd64" | tr a-f A-F)
ManifestType: installer
ManifestVersion: 1.12.0
EOF
cat > "$wg/$id.locale.en-US.yaml" <<EOF
# Generated by packaging/update-packages.sh
# yaml-language-server: \$schema=https://aka.ms/winget-manifest.defaultLocale.1.12.0.schema.json
PackageIdentifier: $id
PackageVersion: $version
PackageLocale: en-US
Publisher: Ratomir Jovanovic
PublisherUrl: https://github.com/ratomirjovanovic
PackageName: PenSec
PackageUrl: https://github.com/ratomirjovanovic/pensec
License: AGPL-3.0-only
LicenseUrl: https://github.com/ratomirjovanovic/pensec/blob/main/LICENSE
ShortDescription: $desc.
Description: PenSec scans your own repository locally, keeps an evidence ledger across sessions and reports undecided controls as plainly as failed ones. Passive by default.
Tags:
  - security
  - appsec
  - sast
  - sarif
ReleaseNotesUrl: https://github.com/ratomirjovanovic/pensec/releases/tag/v$version
ManifestType: defaultLocale
ManifestVersion: 1.12.0
EOF

echo "Wrote Formula/pensec.rb, bucket/pensec.json and packaging/winget/$version for $version."

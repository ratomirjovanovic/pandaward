package adapters

import (
	"fmt"
	"regexp"
	"sort"
	"strings"

	"github.com/ratomirjovanovic/pandaward/internal/inventory"
)

// Java code often reads its hash or cipher algorithm from a properties file
// (props.getProperty("hashAlg1")), which no rule can see. configAlgorithmRules
// reads the project's .properties files and, for each key whose value names
// a weak hash or cipher, writes a taint rule from getProperty("<key>") to
// MessageDigest.getInstance or Cipher.getInstance. It returns nil when no key
// qualifies.

var (
	weakHashValue   = regexp.MustCompile(`(?i)^(MD2|MD4|MD5|SHA|SHA-?1)$`)
	weakCipherValue = regexp.MustCompile(`(?i)^(DES|DESede|TripleDES|RC2|RC4|ARCFOUR|Blowfish)(/.*)?$|^AES$|^[^/]+/ECB(/.*)?$`)
	// propertyKey limits keys to names that are safe to write into a rule.
	propertyKey = regexp.MustCompile(`^[A-Za-z0-9_.-]{1,100}$`)
)

type weakProperty struct{ key, value, file string }

// weakProperties returns the keys of .properties files whose value names a
// weak hash and those whose value names a weak cipher.
func weakProperties(inv *inventory.Inventory) (hashes, ciphers []weakProperty) {
	if inv == nil {
		return nil, nil
	}
	seen := map[string]bool{}
	for _, f := range inv.Files {
		if f.Lang != "properties" {
			continue
		}
		for _, line := range f.Lines {
			line = strings.TrimSpace(line)
			if line == "" || line[0] == '#' || line[0] == '!' {
				continue
			}
			i := strings.IndexAny(line, "=:")
			if i <= 0 {
				continue
			}
			key, value := strings.TrimSpace(line[:i]), strings.TrimSpace(line[i+1:])
			if !propertyKey.MatchString(key) {
				continue
			}
			p := weakProperty{key, value, f.Path}
			switch {
			case weakHashValue.MatchString(value) && !seen["h"+key]:
				seen["h"+key] = true
				hashes = append(hashes, p)
			case weakCipherValue.MatchString(value) && !seen["c"+key]:
				seen["c"+key] = true
				ciphers = append(ciphers, p)
			}
		}
	}
	byKey := func(ps []weakProperty) {
		sort.Slice(ps, func(i, j int) bool { return ps[i].key < ps[j].key })
	}
	byKey(hashes)
	byKey(ciphers)
	return hashes, ciphers
}

func configAlgorithmRules(inv *inventory.Inventory) []byte {
	hashes, ciphers := weakProperties(inv)
	if len(hashes) == 0 && len(ciphers) == 0 {
		return nil
	}
	var b strings.Builder
	b.WriteString("# Generated by PandaWard from the project's .properties files.\nrules:\n")
	rule := func(id, cwe, what, sink string, ps []weakProperty) {
		if len(ps) == 0 {
			return
		}
		names := make([]string, len(ps))
		for i, p := range ps {
			names[i] = fmt.Sprintf("%s=%s in %s", p.key, p.value, p.file)
		}
		fmt.Fprintf(&b, "  - id: %s\n    languages: [java]\n    severity: WARNING\n", id)
		fmt.Fprintf(&b, "    message: %q\n", "The algorithm is read from a properties file that names "+what+" ("+strings.Join(names, "; ")+"). Configure a strong algorithm and do not fall back to a weak default.")
		fmt.Fprintf(&b, "    metadata:\n      pandaward-control: E-004\n      cwe: %q\n", cwe)
		b.WriteString("    mode: taint\n    pattern-sources:\n")
		for _, p := range ps {
			fmt.Fprintf(&b, "      - pattern: $P.getProperty(%q, ...)\n", p.key)
		}
		fmt.Fprintf(&b, "    pattern-sinks:\n      - patterns:\n          - pattern: %s($ALG, ...)\n          - focus-metavariable: $ALG\n", sink)
	}
	rule("pandaward-java-weak-hash-config", "CWE-328: Use of Weak Hash", "a broken hash", "java.security.MessageDigest.getInstance", hashes)
	rule("pandaward-java-weak-cipher-config", "CWE-327: Use of a Broken or Risky Cryptographic Algorithm", "a weak cipher or mode", "javax.crypto.Cipher.getInstance", ciphers)
	return []byte(b.String())
}

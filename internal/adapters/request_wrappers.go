// The bundled Java rules follow taint within a file. A class of the project
// that keeps the servlet request in a field and hands its data out through
// methods (wrapper.getTheParameter("x")) hides that data from them when it
// is used in another file. requestWrapperSources finds such methods: public
// methods returning String whose body uses the request field. Methods that
// do not touch the request (a getter returning a constant) are left out.

var (
	javaPackageRe = regexp.MustCompile(`(?m)^\s*package\s+([\w.]+)\s*;`)
	javaClassRe   = regexp.MustCompile(`\bclass\s+(\w+)`)
	javaReqField  = regexp.MustCompile(`(?m)^\s*(?:(?:private|protected|public|final)\s+)*(?:(?:javax|jakarta)\.servlet\.(?:http\.)?)?(?:HttpServletRequest|ServletRequest)\s+(\w+)\s*;`)
	javaStrMethod = regexp.MustCompile(`(?m)^\s*public\s+(?:final\s+)?(?:java\.lang\.)?String\s+(\w+)\s*\([^)]*\)\s*(?:throws\s+[\w.,\s]+)?\{`)
)

// requestWrapperSources returns Semgrep patterns for the request reading
// methods of wrapper classes, as "(pkg.Class $W).method(...)".
func requestWrapperSources(inv *inventory.Inventory) []string {
	if inv == nil {
		return nil
	}
	var out []string
	for _, f := range inv.Files {
		if f.Lang != "java" || IsTestPath(f.Path) {
			continue
		}
		src := strings.Join(f.Lines, "\n")
		fields := javaReqField.FindAllStringSubmatch(src, -1)
		if len(fields) == 0 {
			continue
		}
		cls := javaClassRe.FindStringSubmatch(src)
		if cls == nil {
			continue
		}
		name := cls[1]
		if m := javaPackageRe.FindStringSubmatch(src); m != nil {
			name = m[1] + "." + name
		}
		for _, loc := range javaStrMethod.FindAllStringSubmatchIndex(src, -1) {
			method := src[loc[2]:loc[3]]
			body := braceBody(src, loc[1]-1)
			for _, fl := range fields {
				use := regexp.MustCompile(`\b(this\.)?` + regexp.QuoteMeta(fl[1]) + `\s*\.\s*\w+\s*\(`)
				if use.MatchString(body) {
					out = append(out, fmt.Sprintf("(%s $W).%s(...)", name, method))
					break
				}
			}
		}
	}
	sort.Strings(out)
	return out
}

// braceBody returns the text between the brace at open and its match.
func braceBody(src string, open int) string {
	depth := 0
	for i := open; i < len(src); i++ {
		switch src[i] {
		case '{':
			depth++
		case '}':
			depth--
			if depth == 0 {
				return src[open+1 : i]
			}
		}
	}
	return src[open+1:]
}

// addRequestSources adds patterns to the shared request sources (the list
// anchored as &request) of the bundled Java rules in dir.
func addRequestSources(dir string, patterns []string) error {
	var block strings.Builder
	for _, p := range patterns {
		fmt.Fprintf(&block, "      - pattern: %s\n", p)
	}
	return insertSources(dir, "java.yaml", block.String())
}

// insertSources puts block, items of the shared request sources, at the
// start of the list anchored as &request in the rule file name.
func insertSources(dir, name, block string, without ...string) error {
	if block == "" {
		return nil
	}
	path := filepath.Join(dir, name)
	b, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	const anchor = "    pattern-sources: &request\n"
	s := string(b)
	i := strings.Index(s, anchor)
	if i < 0 {
		return fmt.Errorf("%s has no shared request sources", name)
	}
	at := i + len(anchor)
	head := "      # Request wrapper classes of this project (generated by PandaWard).\n"
	// The list the anchor started with: it ends at the next key of the rule.
	base := s[at:]
	if end := strings.Index(base, "\n    pattern-"); end >= 0 {
		base = base[:end+1]
	}
	out := s[:at] + head + block + s[at:]
	for _, id := range without {
		out = ownSources(out, id, base)
	}
	return os.WriteFile(path, []byte(out), 0o600)
}

// ownSources gives the rule id its own copy of the shared request sources
// (base), so items added to the shared list do not reach it.
func ownSources(s, id, base string) string {
	i := strings.Index(s, "  - id: "+id+"\n")
	if i < 0 {
		return s
	}
	const ref = "    pattern-sources: *request\n"
	j := strings.Index(s[i:], ref)
	if j < 0 {
		return s
	}
	j += i
	return s[:j] + "    pattern-sources:\n" + base + s[j+len(ref):]
}

var (
	pyClassRe  = regexp.MustCompile(`^class\s+(\w+)\b`)
	pyMethodRe = regexp.MustCompile(`^\s+def\s+(\w+)\s*\(([^)]*)\)`)
	pyStoreRe  = regexp.MustCompile(`^\s+self\.(\w+)\s*(?::[^=]+)?=\s*(\w+)\s*$`)
	pyIdentRe  = regexp.MustCompile(`^\w+$`)
	pyQualRe   = regexp.MustCompile(`^[A-Za-z_][\w.]*$`)
)

// pythonRequestSources finds, in the project's Python modules, classes
// whose __init__ keeps a request parameter (named request or req, or
// annotated with a Request type) in an attribute, and their methods that
// use that attribute. It returns source items for the bundled Python rules:
// $W.method(...) after $W = module.Class(...).
func pythonRequestSources(inv *inventory.Inventory) string {
	if inv == nil {
		return ""
	}
	type wrapper struct {
		qual    string
		methods []string
	}
	var found []wrapper
	for _, f := range inv.Files {
		if f.Lang != "python" || IsTestPath(f.Path) || !strings.HasSuffix(f.Path, ".py") {
			continue
		}
		module := strings.ReplaceAll(strings.TrimSuffix(strings.TrimSuffix(f.Path, ".py"), "/__init__"), "/", ".")
		var cls, def, params string
		var attrs map[string]bool
		var methods, body []string
		endDef := func() {
			if def == "__init__" {
				names := requestParams(params)
				for _, l := range body {
					if m := pyStoreRe.FindStringSubmatch(l); m != nil && names[m[2]] {
						attrs[m[1]] = true
					}
				}
			} else if def != "" {
				text := strings.Join(body, "\n")
				for a := range attrs {
					if strings.Contains(text, "self."+a+".") {
						methods = append(methods, def)
						break
					}
				}
			}
			def, body = "", nil
		}
		endClass := func() {
			endDef()
			if cls != "" && len(methods) > 0 {
				sort.Strings(methods)
				found = append(found, wrapper{module + "." + cls, methods})
			}
			cls, attrs, methods = "", nil, nil
		}
		for _, l := range f.Lines {
			if m := pyClassRe.FindStringSubmatch(l); m != nil {
				endClass()
				cls, attrs = m[1], map[string]bool{}
				continue
			}
			if cls == "" {
				continue
			}
			if strings.TrimSpace(l) != "" && l[0] != ' ' && l[0] != '\t' {
				endClass()
				continue
			}
			if m := pyMethodRe.FindStringSubmatch(l); m != nil {
				endDef()
				def, params = m[1], m[2]
				continue
			}
			if def != "" {
				body = append(body, l)
			}
		}
		endClass()
	}
	sort.Slice(found, func(i, j int) bool { return found[i].qual < found[j].qual })
	var b strings.Builder
	for _, w := range found {
		if !pyQualRe.MatchString(w.qual) {
			continue
		}
		fmt.Fprintf(&b, "      - patterns:\n          - pattern-inside: |\n              $W = %s(...)\n              ...\n          - pattern-either:\n", w.qual)
		for _, m := range w.methods {
			fmt.Fprintf(&b, "              - pattern: $W.%s(...)\n", m)
		}
	}
	return b.String()
}

// requestParams names the parameters of a def that carry a request.
func requestParams(params string) map[string]bool {
	out := map[string]bool{}
	for _, p := range strings.Split(params, ",") {
		name, ann, _ := strings.Cut(strings.TrimSpace(p), ":")
		name = strings.TrimSpace(strings.SplitN(name, "=", 2)[0])
		if !pyIdentRe.MatchString(name) || name == "self" {
			continue
		}
		if name == "request" || name == "req" || strings.Contains(ann, "Request") {
			out[name] = true
		}
	}
	return out
}
